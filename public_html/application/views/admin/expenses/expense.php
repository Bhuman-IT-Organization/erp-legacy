    function expense_items_calc() {
        expense_items_renumber();

        var subtotal = 0;
        var taxTotal = 0;
        var used     = 0;
        var rates    = {};

        $('#expense-items-body .expense-item-row').each(function () {
            var $row = $(this);
            var desc = $.trim($row.find('input.expense-desc').val() || '');
            var qty  = parseFloat($row.find('input.expense-qty').val()) || 0;
            var rate = parseFloat($row.find('input.expense-rate').val()) || 0;
            var pct  = parseFloat($row.find('select.expense-tax').val()) || 0;

            var amount = Math.round(qty * rate * 100) / 100;
            var tax    = Math.round(amount * pct) / 100;

            $row.find('.expense-amount').text(amount.toFixed(2));
            $row.find('.expense-tax-amount').text(tax.toFixed(2));

            // A row with nothing typed in it is the spare row, not a line. Matches
            // Expenses_model::save_expense_items(), which drops the same rows.
            if (desc === '' && rate === 0) {
                return;
            }

            used++;
            subtotal += amount;
            taxTotal += tax;

            if (pct > 0) {
                rates[pct] = true;
            }
        });

        subtotal = Math.round(subtotal * 100) / 100;
        taxTotal = Math.round(taxTotal * 100) / 100;

        $('#expense-items-subtotal').text(subtotal.toFixed(2));
        $('#expense-items-tax').text(taxTotal.toFixed(2));
        $('#expense-items-total').text((Math.round((subtotal + taxTotal) * 100) / 100).toFixed(2));

        var $amount = $('input[name="amount"]');
        var gross   = Math.round((subtotal + taxTotal) * 100) / 100;

        if (used === 0) {
            // No lines in play, hand everything back
            $amount.prop('readonly', false);
            $('#expense-amount-from-items').addClass('hide');
            expense_items_lock_header_tax(false);

            return;
        }

        // The Amount box carries the TAX INCLUSIVE total of the lines, so what is shown
        // is what the expense actually costs - 250.00 of goods plus 5.00 of tax reads
        // 255.00, not 250.00.
        //
        // That means the expense level Tax 1 / Tax 2 must be switched off, because they
        // work as a percentage ON TOP of the amount: leaving Tax 1 at 5% here would make
        // the total 255.00 + 12.75. The per line tax is already inside this figure and is
        // kept line by line in tblexpense_items.
        $amount.val(gross.toFixed(2)).prop('readonly', true).trigger('change');
        $('#expense-amount-from-items').removeClass('hide');
        expense_items_lock_header_tax(true);
    }

