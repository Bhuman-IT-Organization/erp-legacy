    function expense_items_lock_header_tax(locked) {
        $.each(['tax', 'tax2'], function (i, field) {
            var $select = $('select[name="' + field + '"]');
            if (!$select.length) {
                return;
            }

            var hiddenId = 'expense_items_clear_' + field;

            if (locked) {
                if ($select.val() !== '' && $select.val() !== null) {
                    $select.val('');
                    if ($select.hasClass('selectpicker')) {
                        $select.selectpicker('refresh');
                    }
                }
                $select.prop('disabled', true);
                if ($select.hasClass('selectpicker')) {
                    $select.selectpicker('refresh');
                }
                if (!$('#' + hiddenId).length) {
                    $('<input>', {
                        type: 'hidden', id: hiddenId, name: field, value: ''
                    }).insertAfter($select);
                }
            } else {
                $('#' + hiddenId).remove();
                $select.prop('disabled', false);
                if ($select.hasClass('selectpicker')) {
                    $select.selectpicker('refresh');
                }
            }
        });

        $('#expense-items-tax-locked').toggleClass('hide', !locked);
    }

